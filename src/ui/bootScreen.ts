/**
 * Экран загрузки: тонкая обёртка над `window.__boot` из index.html.
 *
 * Сама разметка и анимация живут в index.html — они обязаны появиться раньше
 * бандла, иначе первые секунды первой загрузки остаются белыми. Отсюда игра
 * только сообщает, докуда дошла, и снимает экран, когда сцена собрана.
 *
 * Ничего не ждём и не бросаем: экран — вспомогательный, и если его в документе
 * нет (тесты, съёмка скриншотов на своей странице), игра идёт как обычно.
 */

declare global {
  interface Window {
    /** Мост из index.html; отсутствует, если страница собрана без экрана загрузки. */
    __boot?: { step(value: number): void; done(): void };
  }
}

/** Отметить прогресс старта: 0 — начали, 1 — сцена готова. */
export function bootStep(value: number): void {
  try { window.__boot?.step(value); } catch { /* экрана нет — не критично */ }
}

/** Убрать экран загрузки и показать сцену. Идемпотентно. */
export function bootDone(): void {
  try { window.__boot?.done(); } catch { /* экрана нет — не критично */ }
}
