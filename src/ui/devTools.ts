/**
 * ⚠️ ВРЕМЕННЫЙ ФЛАГ DEV-ИНСТРУМЕНТОВ (кнопки 🛠 / 🎓 / 📊 в топбаре, консольный `__game`).
 * Удалить перед релизом вместе с самими инструментами — см. `devFps.ts` и `buildDevMenu`.
 *
 * Почему не просто `import.meta.env.DEV`: он true только на dev-сервере. В любой сборке
 * (даже `vite build --mode development`) Vite жёстко ставит NODE_ENV=production, поэтому
 * DEV=false, ветки инструментов вырезаются, а `devFps.ts` вытрясается tree-shaking'ом —
 * в архиве кнопок не оказывается. А проверять FPS и отклик надо именно на собранной
 * версии и на реальном телефоне.
 *
 * Собирать NODE_ENV=development ради этого нельзя: тогда в бандл идут отладочные ветки
 * библиотек, и замеры перестают отражать релизную производительность. Поэтому отдельный
 * флаг: сборка остаётся продакшн-сборкой, а инструменты включаются явно.
 *
 *   npm run build       → прод-архив, флага нет, весь dev-код вырезан
 *   npm run build:test  → dist-test с инструментами (режим `devtools`, см. .env.devtools)
 *
 * Значение подставляется на этапе сборки строковым литералом, поэтому в прод-сборке всё
 * выражение сворачивается в `false` и мёртвый код удаляется — проверено grep'ом по бандлу.
 */
export const DEVTOOLS = import.meta.env.DEV || import.meta.env.VITE_DEVTOOLS === '1';
