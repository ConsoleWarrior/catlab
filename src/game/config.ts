/**
 * Выгода пака относительно самого мелкого, % (для бейджа «+31%»). Считается из
 * реальных чисел, а не задаётся руками, — поменяли цену, и подпись не соврёт.
 */
export function packBonusPct(pack: CrystalPack): number {
  const base = CRYSTAL_PACKS[0]!;
  if (pack.id === base.id || base.yans <= 0 || pack.yans <= 0) return 0;
  const baseRate = base.crystals / base.yans;
  return Math.round((pack.crystals / pack.yans / baseRate - 1) * 100);
}

/** Опыт, нужный для следующего уровня (null — уже максимум). Для прогресс-бара в HUD. */
export function nextLevelRep(level: number): number | null {
  return level >= MAX_LEVEL ? null : LEVEL_REP_THRESHOLDS[level]!; // порог для уровня (level+1)
}

/**
 * 💎 в подарок за достижение уровня лаборатории. Со 2-го уровня: 6, 9, 12, …, 30
 * (ровно 3 × уровень). Уровень 1 — старт (подарка нет), выше MAX_LEVEL — 0.
 * Начисляется в actions.addReputation при пересечении порога; панель повышения
 * уровня (ui) показывает эту же сумму.
 */
export function levelCrystalReward(level: number): number {
  if (level < 2 || level > MAX_LEVEL) return 0;
  return 3 * level;
}

/**
 * Что открывается РОВНО на данном уровне — строки для панели «Уровень N!».
 * Перечисляем всё, что гейтит уровень лаборатории: слоты вязки, пьедесталы,
 * фичи-комнаты (кормушка/усилители/стол рецептов) и узлы дерева «Улучшений»,
 * чей ПЕРВЫЙ уровень открывается для покупки именно на этом уровне (в т.ч.
 * «На эксперименты», «Ветеринар», «Криогенетика» — они докупаются в дереве).
 */
export function unlocksAtLevel(level: number): string[] {
  const out: string[] = [];
  const slotIdx = SLOT_UNLOCK_LEVELS.indexOf(level);
  if (slotIdx >= 0) out.push(t(`💞 слот вязки №${slotIdx + 2}`, `💞 breeding slot #${slotIdx + 2}`));
  const pedIdx = PEDESTAL_UNLOCK_LEVELS.indexOf(level);
  if (pedIdx >= 0) out.push(t(`🏆 пьедестал №${pedIdx + 2}`, `🏆 pedestal #${pedIdx + 2}`));
  // Фичи-покупки (labStation/clinic/engineering) сюда не входят — их анонсирует
  // цикл по RESEARCH ниже, по узлу-разблокировке.
  const featNames: Partial<Record<LabFeature, string>> = {
    food: t('🍽 кормушка', '🍽 feeder'),
    research: t('🔬 улучшения', '🔬 upgrades'),
    recipeLab: t('🧪 исследование рецептов', '🧪 recipe research'),
  };
  for (const key of Object.keys(featNames) as LabFeature[]) {
    if (LAB_UNLOCKS[key] === level) out.push(featNames[key]!);
  }
  // Узлы дерева «Улучшений» (Генолаб): анонсируем узел, когда его ПЕРВЫЙ уровень
  // становится доступен для покупки на этом уровне лаборатории (levels[0].minLevel).
  for (const def of RESEARCH) {
    if (def.levels[0]?.minLevel === level) out.push(`${def.glyph} ${tx(def.title)}`);
  }
  return out;
}
