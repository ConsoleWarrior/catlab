// сам сменяется новым (refreshExpiredOrders). Выполнил — слот сразу получает свежий
// заказ. Плюс у КАЖДОГО слота свой кулдаун ORDER_AD_REFRESH_COOLDOWN_MS на 📺-обновление.
export const ORDER_TARGET = 4;                         // сколько слотов на доске заказов
export const ORDER_REFRESH_MS = 6 * 60 * 60_000;       // 6 ч жизни заказа: не выполнил → сменится новым
export const ORDER_AD_REFRESH_COOLDOWN_MS = 60 * 60_000; // 📺-обновление слота — раз в час (у каждого слота свой)
export const ORDER_COIN_MULT = 1.0;           // заказ платит ≈ полную рыночную цену
export const ORDER_DNA_MULT = 0.06;           // 🧬-бонус за заказ (доля ценности)
// ⭐ за заказ считается ПЛАВНО от скрытого уровня заказанной породы (breedLevel 1..10),
// а НЕ от её тира: тир — ступенька (соседние породы разных тиров отличались втрое), и
// награда прыгала на тех уровнях лаборатории, где пул заказов менял тир (L4/L7/L9), тогда
// как пороги уровней растут плавно. Геометрия по уровню породы убирает эти ступени:
// ⭐ = round(BASE × GROWTH^(уровень породы − 1)) → 26/35/48/65/89/121/164/223/304/414.
// Монеты/🧬 за заказ по-прежнему ∝ рыночной ценности эталона (там ступень тира уместна —
// это цена кота), ⭐ отвязан от неё намеренно.
export const ORDER_REP_BASE = 26;             // ⭐ за заказ на породу 1-го скрытого уровня
export const ORDER_REP_GROWTH = 1.36;         // ×⭐ за каждый следующий уровень породы

/** ⭐ за заказ по скрытому уровню породы (1..10) — плавная геометрия, без ступеней тира. */
export function orderRepFor(breedLevel: number): number {
  const l = Math.max(1, breedLevel);
  return Math.round(ORDER_REP_BASE * ORDER_REP_GROWTH ** (l - 1));
}

// --- Опыт (репутация) за важные действия ---
// Опыт (⭐) копится не только с заказов, но и с рождений/продаж/сдачи в лабораторию.
// Награда за рождение — от РЫНОЧНОЙ ЦЕННОСТИ котёнка (catMarketValue), с ×множителем за
// ПЕРВОЕ открытие породы (коллекционирование — ядро игры).
// Раньше считалась от голого TIER_MARKET_VALUE[тир]: труднейшая порода тира и простейшая
// давали одинаковый опыт, а родословная не значила ничего. Теперь база та же, что у
// пристройства/лаборатории/дохода — порода внутри тира (×0.8..1.6), родословная (до ×1.8)
// и здоровье (инбридинг режет) сразу отражаются в ⭐ за рождение.
// Ставка поднята 0.027 → 0.04: селекция не должна цениться ниже утилизации того же кота
// (сдача в лабораторию — 0.05, но кот при этом уезжает навсегда). Вместе со сменой базы это
// даёт примерно ×2 к прежнему опыту за рождение: ≈ 3/11/28/70/172 ⭐ по тирам T1..T5 у
// типового котёнка с родословной. Выше не берём — рождение стало бы главным краном опыта и
// съело бы целевой темп «1-2 месяца» (при 0.075 прохождение ускорялось вдвое).
export const REP_BIRTH_RATE = 0.04;           // ⭐ за рождение = round(catMarketValue × rate)
// Множитель за первое открытие породы срезан 5 → 3: опыт за рождение теперь считается от
